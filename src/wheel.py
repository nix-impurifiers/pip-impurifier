import base64
import csv
import hashlib
import io
import json
from pathlib import Path
import sys
import zipfile

payload, config, output = map(Path, sys.argv[1:])
options = json.loads(config.read_text())
name = options['name'].replace('-', '_')
version = options['version']
dist = f'{name}-{version}.dist-info'
files = {}
for path in sorted(payload.rglob('*')):
    if path.is_symlink():
        raise ValueError('wheel payload symlinks must be materialized by the producer')
    if path.is_file():
        relative = path.relative_to(payload).as_posix()
        if any(part.endswith('.dist-info') for part in path.relative_to(payload).parts):
            raise ValueError('wheel metadata is generated by the emitter')
        files[relative] = path.read_bytes()
metadata = f"Metadata-Version: 2.3\nName: {options['name']}\nVersion: {version}\nSummary: {options['summary']}\n"
for dependency in options['dependencies']:
    metadata += 'Requires-Dist: ' + dependency + '\n'
files[dist + '/METADATA'] = (metadata + '\n').encode()
files[dist + '/WHEEL'] = f"Wheel-Version: 1.0\nGenerator: pip-impurifier\nRoot-Is-Purelib: {str(options['pure']).lower()}\nTag: {options['tag']}\n".encode()
if options['entryPoints']:
    files[dist + '/entry_points.txt'] = ('[console_scripts]\n' + ''.join(f'{k} = {v}\n' for k,v in options['entryPoints'].items())).encode()
record = io.StringIO(newline='')
writer = csv.writer(record,lineterminator='\n')
for relative, data in sorted(files.items()):
    digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b'=').decode()
    writer.writerow([relative, 'sha256='+digest, len(data)])
writer.writerow([dist + '/RECORD', '', ''])
files[dist + '/RECORD'] = record.getvalue().encode()
with zipfile.ZipFile(output,'w',compression=zipfile.ZIP_DEFLATED) as archive:
    for relative,data in sorted(files.items()):
        info=zipfile.ZipInfo(relative,(1980,1,1,0,0,0))
        info.compress_type=zipfile.ZIP_DEFLATED
        info.external_attr=0o100644 << 16
        archive.writestr(info,data)
